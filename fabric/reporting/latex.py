"""LaTeX rendering.

Produces a standalone article and, more usefully, tables that can be
included directly in a paper.  The point is not that anyone submits this
document as-is; it is that the results table in the paper and the results
table in the report are generated from the same numbers, so they cannot
disagree.

Charts are emitted as ``tabular`` summaries rather than TikZ: a table
that compiles everywhere beats a picture that needs three packages.
"""

from __future__ import annotations

import time
from collections.abc import Sequence
from typing import Any

from fabric.reporting.document import (
    Block,
    Bullets,
    Callout,
    Chart,
    Code,
    Document,
    GraphView,
    KeyValues,
    Paragraph,
    Table,
)

PREAMBLE = r"""\documentclass[11pt]{article}
\usepackage[margin=1in]{geometry}
\usepackage{booktabs}
\usepackage{longtable}
\usepackage{array}
\usepackage{xcolor}
\usepackage{hyperref}
\usepackage[T1]{fontenc}
\hypersetup{colorlinks=true, linkcolor=black, urlcolor=blue}
\setlength{\parskip}{0.5em}
\setlength{\parindent}{0pt}
"""

_ESCAPES = {
    "\\": r"\textbackslash{}",
    "&": r"\&",
    "%": r"\%",
    "$": r"\$",
    "#": r"\#",
    "_": r"\_",
    "{": r"\{",
    "}": r"\}",
    "~": r"\textasciitilde{}",
    "^": r"\textasciicircum{}",
    "±": r"$\pm$",
    "Δ": r"$\Delta$",
    "×": r"$\times$",
    "≥": r"$\geq$",
    "≤": r"$\leq$",
    "—": "---",
    "–": "--",
    "’": "'",
    "“": "``",
    "”": "''",
}


def escape(text: Any) -> str:
    """Escape a string for LaTeX."""
    out = []
    for char in str(text):
        out.append(_ESCAPES.get(char, char))
    return "".join(out)


def _column_spec(aligns: Sequence[str], count: int) -> str:
    spec = []
    for index in range(count):
        align = aligns[index] if index < len(aligns) else "left"
        spec.append({"right": "r", "center": "c"}.get(align, "l"))
    return "".join(spec)


def render_table(table: Table, *, environment: str = "tabular") -> str:
    """Render one table as a booktabs ``tabular``."""
    columns = _column_spec(table.aligns, len(table.headers))
    lines = [rf"\begin{{{environment}}}{{{columns}}}", r"\toprule"]
    lines.append(" & ".join(rf"\textbf{{{escape(h)}}}" for h in table.headers) + r" \\")
    lines.append(r"\midrule")
    for row_index, row in enumerate(table.rows):
        cells = [escape(c) for c in row]
        if row_index in table.emphasise:
            cells = [rf"\textbf{{{c}}}" for c in cells]
        lines.append(" & ".join(cells) + r" \\")
    lines.append(r"\bottomrule")
    lines.append(rf"\end{{{environment}}}")
    return "\n".join(lines)


def render_float(table: Table, *, label: str = "") -> str:
    """Wrap a table in a numbered, captioned float."""
    parts = [r"\begin{table}[htbp]", r"\centering", r"\small"]
    parts.append(render_table(table))
    if table.caption:
        parts.append(rf"\caption{{{escape(table.caption)}}}")
    if label:
        parts.append(rf"\label{{tab:{label}}}")
    parts.append(r"\end{table}")
    return "\n".join(parts)


def _render_block(block: Block) -> str:
    if isinstance(block, Paragraph):
        return escape(block.text)
    if isinstance(block, Bullets):
        environment = "enumerate" if block.ordered else "itemize"
        items = "\n".join(rf"  \item {escape(i)}" for i in block.items)
        return f"\\begin{{{environment}}}\n{items}\n\\end{{{environment}}}"
    if isinstance(block, KeyValues):
        lines = [r"\begin{description}[leftmargin=!]" if False else r"\begin{description}"]
        for key, value in block.pairs:
            lines.append(rf"  \item[{escape(key)}] {escape(value)}")
        lines.append(r"\end{description}")
        return "\n".join(lines)
    if isinstance(block, Table):
        return render_float(block)
    if isinstance(block, Callout):
        text = f" {escape(block.text)}" if block.text else ""
        return rf"\par\noindent\textbf{{{escape(block.title)}.}}{text}\par"
    if isinstance(block, Code):
        return (r"\begin{verbatim}" + "\n" + block.text + "\n" + r"\end{verbatim}")
    if isinstance(block, GraphView):
        return (rf"\par\noindent\textit{{{escape(block.caption)}}}\par"
                if block.caption else "")
    if isinstance(block, Chart):
        # Charts carry no information the tables do not; the caption keeps
        # the reference so a figure can be dropped in later.
        return rf"\par\noindent\textit{{{escape(block.caption)}}}\par" if block.caption else ""
    return ""


def render(document: Document, *, standalone: bool = True) -> str:
    """Render a document to LaTeX."""
    metadata = document.metadata
    generated = time.strftime("%Y-%m-%d", time.gmtime(metadata.get("generated_at", time.time())))

    body: list[str] = []
    if standalone:
        body.append(PREAMBLE)
        body.append(rf"\title{{{escape(document.title)}}}")
        body.append(r"\author{Generated by Experiment Fabric}")
        body.append(rf"\date{{{escape(generated)}}}")
        body.append(r"\begin{document}")
        body.append(r"\maketitle")
        if document.subtitle:
            body.append(r"\begin{abstract}")
            body.append(escape(document.subtitle))
            body.append(r"\end{abstract}")
        body.append(
            rf"\noindent\texttt{{{escape(metadata.get('experiment_id', ''))}}} "
            rf"$\cdot$ {escape(metadata.get('n_runs', 0))} runs $\cdot$ primary metric "
            rf"\texttt{{{escape(metadata.get('primary_metric', ''))}}} $\cdot$ "
            rf"$\alpha={escape(metadata.get('alpha', ''))}$ with "
            rf"{escape(metadata.get('correction', ''))} correction."
        )
        body.append(r"\tableofcontents")

    for depth, section in document.walk():
        if section.is_empty and not section.summary:
            continue
        command = {1: "section", 2: "subsection"}.get(depth, "subsubsection")
        body.append(rf"\{command}{{{escape(section.title)}}}")
        for block in section.blocks:
            rendered = _render_block(block)
            if rendered:
                body.append(rendered)

    if standalone:
        body.append(r"\end{document}")
    return "\n\n".join(body) + "\n"


def render_tables(document: Document) -> dict[str, str]:
    """Extract every table as a standalone snippet, keyed by a label.

    This is the practical output: ``\\input{tables/results.tex}`` in the
    paper, regenerated whenever the experiment is rerun, so the paper
    cannot fall out of step with the evidence.
    """
    snippets: dict[str, str] = {}
    counts: dict[str, int] = {}
    for _depth, section in document.walk():
        for block in section.blocks:
            if not isinstance(block, Table):
                continue
            base = section.anchor
            counts[base] = counts.get(base, 0) + 1
            suffix = "" if counts[base] == 1 else f"-{counts[base]}"
            snippets[f"{base}{suffix}"] = render_float(block, label=f"{base}{suffix}")
    return snippets
